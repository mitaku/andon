# === 29. レビューを頼む前の反論の段（worker skill §2・§3・§4・§7） ===
# 1回目のレビューで返る major の多くが、包む呼び出し元・並行の実行・無い入力・片方だけ欠ける入力・たどる循環の見落としだった。
# 担当が足した検査を、見ていない書き方の入力や、確かめる分岐を通らない ok の道が素通りした major も重なった。担当が決まった一覧の変種を
# 当てても、素通りは一覧の外だった。そこで6つ目の観点（足した検査の素通り）として反論役に、検査の意味から変種を作らせる。
# 名指した当てたあとの検証の道が変えた振る舞いを通らない major も、1回目のレビューで重なった。これは repo の REVIEW.md の項目で、
# 反論役は REVIEW.md を渡されず、その項目で差分を壊さなかった。そこで渡すものに REVIEW.md のパスを足し、その項目でも壊させる。
# その後、反論役が検証の道の疑いを出しても、担当は落ちる検査を書けないとして捨て、1回目のレビューで同じ点が major になった。
# 検証の道は地図の手順と段の読みで当たりが決まり、落ちる検査に書けない。そこで検証の道の疑いだけは捨てず、地図を読んで確かめ、
# 当たれば同じ PR で地図に足すか、足さない理由をトレードオフに書かせる。ほかの疑いまで捨てる線を緩めないよう、この項目に限る。
# その後も、反論役が近い疑いを出していたのに、1回目のレビューで同じ種類の入力が major になった。直した疑い（読めない隣）の変種
# （探索できない隣）を当てなかった回と、件数で合う照合の直しが足りなかった回と、疑い（コードフェンスの中の見出し）を「本文は残る」と
# 理由だけで捨てた回があった。そこで直した疑いは同じ道を通る変種にも検査を書いて当て、捨てる疑いはその入力で書いた検査が
# 通るのを見てから捨てさせる。変種を探し続けないよう、書き出した変種を当てたら終える線も置く。
# 担当がレビューの前に拾う段が skill から消えたり、観点や確かめ方が抜けたりしたら落とす。
# 確かめ方・直した疑いの変種・捨てる疑いの行の決めた文（丸ごと比べる）
rebuttal_check='- **確かめ方**: 返った疑いを1件ずつ、今の `HEAD` で落ちる検査に書けるか試す（反論役は書かないので、自分で書く）。落ちる検査を書けた疑いだけを直す。直したら検査が通ること、直しを戻すと落ちることを確かめ、検査ごと commit する。落ちる検査を書けない疑い（疑いの入力で書いた検査が今の `HEAD` で通る・起きる入力を作れない）は捨て、直さない。'
rebuttal_variant='- **直した疑いの変種**: 落ちる検査を書けて直した疑いは、同じ種類の入力の変種を書き出し、変種ごとにも検査を書いて当てる。変種は、疑いの入力と同じ道（同じ関数・同じ照合）を通り、別の形で同じ誤りになる入力に限る。例は、読めない入力に対する探索できない・一覧できない入力、見出しの照合に対するコードフェンスの中の行、件数の照合に対する件数だけ合う別の中身。落ちた変種は同じに直し、通った変種の検査も残して、検査ごと commit する。書き出した変種を当てたら終え、同じ道を通らない入力まで探し続けない。'
rebuttal_drop='- **捨てる疑い**: 理由だけで捨てない（「本文は残る」「その入力は来ない」と読んで捨てない）。捨てる前に、反論役が返した起きる条件の入力で検査を書き、今の `HEAD` で通ることを見る。通った検査は、その入力を守る検査として commit する。起きる条件の入力を作れない疑い（セルに無い権限や外のサービスが要るなど）と、起きる条件を入力と結果で書けない疑い（文書の読み手・設計との食い違い・決定の記録の有無など、読んで決まるもの）だけは、その理由を `反論:` の行に書いて捨てる。当てたあとの検証の道の疑いは、下の段のとおり地図で確かめて捨てる。'
# 段の全体（見出しの行から §4 の 1 の手前まで）と §7 の「反論:」の雛形の行の控え。どの箇条や観点の行に捨ててよい道を
# 足しても落とすため、丸ごと比べる。段か雛形の行を変えたら、意図した変更かを読んでから、rebuttal_miss が出す値をここに写す。
rebuttal_want_sum=4e5c66720a3194e5244d6449c506831cd87b379b0baa0bfc6d5b9c1d59fa84f4
# rebuttal_sum=off のときは控えを比べない（下の写しの検査で、ほかの判定が当たることを1つずつ見るため）
rebuttal_sum=on
# rebuttal_miss <worker SKILL.md>: 足りないものを1行で出す（空なら合っている）
rebuttal_miss() {
  local m='' s2 s3 s4 s7 block views
  s2=$(sed -n '/^## 2\. /,/^## 3\. /p' "$1"); s3=$(sed -n '/^## 3\. /,/^## 4\. /p' "$1")
  s4=$(sed -n '/^## 4\. /,/^## 5\. /p' "$1"); s7=$(sed -n '/^## 7\. /,$p' "$1")
  block=$(sed -n '/^\*\*1回目を頼む前に、反論の段を通す\*\*/,/^1\. PR を出したらすぐ頼む/p' <<<"$s4" | sed '$d')
  [ -n "$block" ] || { echo " [worker §4 に「1回目を頼む前に、反論の段を通す」の段が、§4 の 1 の前に無い]"; return; }
  grep -q '^- \*\*渡すもの\*\*:.*`origin/main` との差分.*依頼書のパスと、repo に `REVIEW.md` があればそのパスだけ' <<<"$block" || m="$m [渡すもの: origin/main との差分と依頼書と REVIEW.md だけ]"
  # REVIEW.md の項目でも壊させる（レビュアーが同じ項目で見るので、項目による major をレビューの前に拾う）
  grep -q '^- \*\*`REVIEW.md` の項目\*\*:.*その項目ごとにも差分を壊させる' <<<"$block" || m="$m [REVIEW.md の項目でも壊させること]"
  grep -q '^- \*\*サブエージェントを起動できないプロファイル\*\*.*`REVIEW.md` があればその項目ごとにも書き出して' <<<"$block" || m="$m [自分で通すときも REVIEW.md の項目]"
  grep -q '^- \*\*頼み方\*\*:.*読むだけのサブエージェント' <<<"$block" || m="$m [頼み方: 読むだけのサブエージェント]"
  views=$(sed -n 's/^  [0-9]\. \*\*\([^*]*\)\*\*.*/\1/p' <<<"$block" | tr '\n' '|')
  [ "$views" = '包む呼び出し元|並行の実行|無い・空・読めない入力|片方だけ欠ける入力|たどる循環|足した検査の素通り|' ] || m="$m [6つの観点の見出し: $views]"
  # 観点の数を言う文（段の頭・頼み方・自分で通すとき）が、並べた観点の数と同じ
  for n in '下の6つの観点の見落とし' '次の6つの観点を名指しする' '6つの観点ごとに疑いを書き出し'; do
    grep -qF -- "$n" <<<"$block" || m="$m [観点の数の文「$n」]"
  done
  # 6つ目の観点は、素通りする入力と確かめる分岐を通らない ok の道の両方を名指しし、例の外の変種を反論役に作らせる
  view6=$(grep '^  6\. \*\*足した検査の素通り\*\*' <<<"$block")
  grep -qF '検査の見ていない書き方で書いた入力' <<<"$view6" || m="$m [観点 6 に素通りする入力]"
  grep -qF '確かめる分岐を通らずに ok になる道' <<<"$view6" || m="$m [観点 6 に分岐を通らない ok の道]"
  grep -qF '例の外も、検査の意味から変種を作って試す' <<<"$view6" || m="$m [観点 6 に例の外の変種を作らせること]"
  grep -q '^- \*\*確かめ方\*\*:.*落ちる検査を書けた疑いだけを直す.*落ちる検査を書けない疑い.*は捨て' <<<"$block" || m="$m [確かめ方: 落ちる検査を書けた疑いだけを直し、書けなければ捨てる]"
  # 直した疑いは、同じ道を通る変種にも検査を書いて当てる。例は根拠の出来事の入力で、書き出した分で終える
  local variant drop
  variant=$(grep '^- \*\*直した疑いの変種\*\*:' <<<"$block")
  for n in '落ちる検査を書けて直した疑いは、同じ種類の入力の変種を書き出し、変種ごとにも検査を書いて当てる' '疑いの入力と同じ道（同じ関数・同じ照合）を通り' '探索できない・一覧できない入力' 'コードフェンスの中の行' '件数だけ合う別の中身' '通った変種の検査も残して' '書き出した変種を当てたら終え、同じ道を通らない入力まで探し続けない'; do
    grep -qF -- "$n" <<<"$variant" || m="$m [直した疑いの変種: 「$n」]"
  done
  # 捨てる疑いは理由だけで捨てず、その入力で書いた検査が通るのを見てから捨て、通った検査を残す
  drop=$(grep '^- \*\*捨てる疑い\*\*:' <<<"$block")
  for n in '理由だけで捨てない' '捨てる前に、反論役が返した起きる条件の入力で検査を書き、今の `HEAD` で通ることを見る' '通った検査は、その入力を守る検査として commit する' '起きる条件の入力を作れない疑い（セルに無い権限や外のサービスが要るなど）と、' '起きる条件を入力と結果で書けない疑い（文書の読み手・設計との食い違い・決定の記録の有無など、読んで決まるもの）だけは、その理由を `反論:` の行に書いて捨てる'; do
    grep -qF -- "$n" <<<"$drop" || m="$m [捨てる疑い: 「$n」]"
  done
  # 語の断片が在っても、同じ行に捨ててよい道を足すと決まりが抜ける。確かめ方・変種・捨てる疑いの3行は丸ごと比べ、
  # 段の箇条の見出しの並びも比べる（別の箇条を足して捨ててよい道を書く変種を落とす）
  [ "$(grep '^- \*\*確かめ方\*\*:' <<<"$block")" = "$rebuttal_check" ] || m="$m [確かめ方の行が決めた文と違う]"
  [ "$variant" = "$rebuttal_variant" ] || m="$m [直した疑いの変種の行が決めた文と違う]"
  [ "$drop" = "$rebuttal_drop" ] || m="$m [捨てる疑いの行が決めた文と違う]"
  local heads
  heads=$(sed -n 's/^- \*\*\([^*]*\)\*\*.*/\1/p' <<<"$block" | tr '\n' '|')
  [ "$heads" = '渡すもの|頼み方|`REVIEW.md` の項目|確かめ方|直した疑いの変種|捨てる疑い|当てたあとの検証の道の疑い|起動してよい|サブエージェントを起動できないプロファイル|残し方|' ] || m="$m [段の箇条の見出し: $heads]"
  # 箇条の続きの行（字下げの行など）に捨ててよい道を書く変種も落とす。段は見出しの行・箇条・観点・空の行だけ
  [ -z "$(grep -v '^\*\*1回目を頼む前に、反論の段を通す\*\*\|^- \*\*\|^  [0-9]\. \*\*\|^$' <<<"$block")" ] || m="$m [段に箇条でない行がある]"
  # 検証の道の疑いは捨てずに地図で確かめ、足すか足さない理由をトレードオフに書く。扱いはこの項目に限る
  vpath=$(grep '^- \*\*当てたあとの検証の道の疑い\*\*:' <<<"$block")
  # skill が写す項目の番号が、この repo の REVIEW.md の当てたあとの検証の道の項目の番号と同じ
  local rnum snum
  rnum=$(sed -n 's/^\([0-9][0-9]*\)\. \*\*変えた振る舞いを、当てたあとの検証の道が通るか。\*\*.*/\1/p' REVIEW.md)
  snum=$(sed -n 's/.*検証の道が通るか（Andon の repo では項目 \([0-9][0-9]*\)）.*/\1/p' <<<"$vpath")
  if [ -z "$rnum" ] || [ "$rnum" != "$snum" ]; then m="$m [検証の道の項目の番号: REVIEW.md は「$rnum」、skill は「$snum」]"; fi
  # 扱う疑いを検証の道の項目から出たものに限る主語と、確かめ方と、当たらないときの捨て方
  grep -q '^- \*\*当てたあとの検証の道の疑い\*\*: `REVIEW.md` の項目のうち、変えた振る舞いを当てたあとの検証の道が通るか（[^）]*）から出た疑いは、落ちる検査を書けなくても捨てない' <<<"$vpath" || m="$m [検証の道の疑い: 扱う疑いを検証の道の項目に限る主語]"
  for n in '変えた振る舞いを打つか、その見える証拠を挙げるかで確かめる' '既にある細かい機能が変えた振る舞いを打っていれば当たらない疑いで、直さず捨てる' '落ちる検査を書けなくても捨てない' '細かい機能の手順と段' '同じ PR で細かい機能か手順を足す' '理由を PR 本文の「トレードオフ」に書く' 'この扱いはこの項目の疑いだけ'; do
    grep -qF -- "$n" <<<"$vpath" || m="$m [検証の道の疑い: 「$n」]"
  done
  grep -q '^- \*\*サブエージェントを起動できないプロファイル\*\*.*自分で通す' <<<"$block" || m="$m [サブエージェントを起動できないときの通し方]"
  grep -q '^- \*\*残し方\*\*:.*`反論:` の行' <<<"$block" || m="$m [残し方: 報告の反論の行]"
  grep -q '^| 確認 |.*1回目を頼む前の反論の段（§4）' <<<"$s2" || m="$m [worker §2 の工程表の確認に反論の段]"
  grep -q '^3\. PR を出す（.*出す前に §4 の反論の段を通す' <<<"$s3" || m="$m [worker §3 の 3 に反論の段]"
  grep -q '^1\. PR を出したらすぐ頼む（反論の段〈上〉の行' <<<"$s4" || m="$m [worker §4 の 1 に反論の段の行]"
  grep -q '^反論: <.*疑い N 件.*直した M 件.*捨てた K 件.*1回目を頼むとき' <<<"$s7" || m="$m [worker §7 の書式に「反論:」の行]"
  # 自分で通した（Codex など）ときも REVIEW.md の項目を当てたかが、当てたあとの検証で報告から読めるよう、行に件数を書かせる
  grep -q '^反論: <.*疑い N 件（うち `REVIEW.md` の項目から L 件' <<<"$s7" || m="$m [worker §7 の「反論:」の行に REVIEW.md の項目の件数]"
  # 検証の道の疑いを地図に足したか・足さずにトレードオフに書いたかが、当てたあとの検証で報告から読めるよう、行に件数を書かせる
  grep -q '^反論: <.*検証の道の疑いは、地図に足した J 件（' <<<"$s7" || m="$m [worker §7 の「反論:」の行に検証の道の疑いの件数]"
  # 件数だけでは、疑いと別の細かい機能を変えても合ってしまう。足した細かい機能の名前を疑いごとに書かせ、検証で突き合わせる
  grep -q '^反論: <.*地図に足した J 件（<疑いごとに足した細かい機能の名前>）と、足さずにトレードオフに書いた G 件' <<<"$s7" || m="$m [worker §7 の「反論:」の行に足した細かい機能の名前]"
  # 変種を当てたか・捨てる前に検査を書いたかが、当てたあとの検証で報告から読めるよう、件数と検査の名前を書かせる
  # 担当が写すのは雛形の「反論:」の行なので、§7 のほかの行に同じ文があっても数えない
  local rline
  rline=$(grep '^反論: <' <<<"$s7")
  # 雛形の行は1本だけ（前の形の雛形を残し、新しい文の行を別に足す変種を落とす）
  [ "$(grep -c '^反論: <' <<<"$s7")" = 1 ] || m="$m [worker §7 の「反論:」の雛形の行が1本でない]"
  if [ "$rebuttal_sum" != off ]; then
    local sum
    sum=$(printf '%s\n%s\n' "$block" "$rline" | sha256sum | cut -d' ' -f1)
    [ "$sum" = "$rebuttal_want_sum" ] || m="$m [段か「反論:」の雛形の行が控えと違う（意図した変更なら控えを $sum に）]"
  fi
  grep -qF '直した疑いの変種は V 件当て（<変種ごとの検査の名前>）、うち落ちて直した U 件' <<<"$rline" || m="$m [worker §7 の「反論:」の行に変種の件数と検査の名前]"
  grep -qF '捨てた K 件（<捨てた疑いごとに、その入力で書いて通った検査の名前・入力を作れないか入力と結果で書けない理由・既に通す細かい機能の名前のどれか>）' <<<"$rline" || m="$m [worker §7 の「反論:」の行に捨てた疑いごとの検査の名前]"
  echo "$m"
}
