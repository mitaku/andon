# === 29. レビューを頼む前の反論の段（worker skill §2・§3・§4・§7） ===
# 1回目のレビューで返る major の多くが、包む呼び出し元・並行の実行・無い入力・片方だけ欠ける入力・たどる循環の見落としだった。
# 担当が足した検査を、見ていない書き方の入力や、確かめる分岐を通らない ok の道が素通りした major も重なった。担当が決まった一覧の変種を
# 当てても、素通りは一覧の外だった。そこで6つ目の観点（足した検査の素通り）として反論役に、検査の意味から変種を作らせる。
# 名指した当てたあとの検証の道が変えた振る舞いを通らない major も、1回目のレビューで重なった。これは repo の REVIEW.md の項目で、
# 反論役は REVIEW.md を渡されず、その項目で差分を壊さなかった。そこで渡すものに REVIEW.md のパスを足し、その項目でも壊させる。
# その後、反論役が検証の道の疑いを出しても、担当は落ちる検査を書けないとして捨て、1回目のレビューで同じ点が major になった。
# 検証の道は地図の手順と段の読みで当たりが決まり、落ちる検査に書けない。そこで検証の道の疑いだけは捨てず、地図を読んで確かめ、
# 当たれば同じ PR で地図に足すか、足さない理由をトレードオフに書かせる。ほかの疑いまで捨てる線を緩めないよう、この項目に限る。
# 担当がレビューの前に拾う段が skill から消えたり、観点や確かめ方が抜けたりしたら落とす。
# rebuttal_miss <worker SKILL.md>: 足りないものを1行で出す（空なら合っている）
rebuttal_miss() {
  local m='' s2 s3 s4 s7 block views
  s2=$(sed -n '/^## 2\. /,/^## 3\. /p' "$1"); s3=$(sed -n '/^## 3\. /,/^## 4\. /p' "$1")
  s4=$(sed -n '/^## 4\. /,/^## 5\. /p' "$1"); s7=$(sed -n '/^## 7\. /,$p' "$1")
  block=$(sed -n '/^\*\*1回目を頼む前に、反論の段を通す\*\*/,/^1\. PR を出したらすぐ頼む/p' <<<"$s4" | sed '$d')
  [ -n "$block" ] || { echo " [worker §4 に「1回目を頼む前に、反論の段を通す」の段が、§4 の 1 の前に無い]"; return; }
  grep -q '^- \*\*渡すもの\*\*:.*`origin/main` との差分.*依頼書のパスと、repo に `REVIEW.md` があればそのパスだけ' <<<"$block" || m="$m [渡すもの: origin/main との差分と依頼書と REVIEW.md だけ]"
  # REVIEW.md の項目でも壊させる（レビュアーが同じ項目で見るので、項目による major をレビューの前に拾う）
  grep -q '^- \*\*`REVIEW.md` の項目\*\*:.*その項目ごとにも差分を壊させる' <<<"$block" || m="$m [REVIEW.md の項目でも壊させること]"
  grep -q '^- \*\*サブエージェントを起動できないプロファイル\*\*.*`REVIEW.md` があればその項目ごとにも書き出して' <<<"$block" || m="$m [自分で通すときも REVIEW.md の項目]"
  grep -q '^- \*\*頼み方\*\*:.*読むだけのサブエージェント' <<<"$block" || m="$m [頼み方: 読むだけのサブエージェント]"
  views=$(sed -n 's/^  [0-9]\. \*\*\([^*]*\)\*\*.*/\1/p' <<<"$block" | tr '\n' '|')
  [ "$views" = '包む呼び出し元|並行の実行|無い・空・読めない入力|片方だけ欠ける入力|たどる循環|足した検査の素通り|' ] || m="$m [6つの観点の見出し: $views]"
  # 観点の数を言う文（段の頭・頼み方・自分で通すとき）が、並べた観点の数と同じ
  for n in '下の6つの観点の見落とし' '次の6つの観点を名指しする' '6つの観点ごとに疑いを書き出し'; do
    grep -qF -- "$n" <<<"$block" || m="$m [観点の数の文「$n」]"
  done
  # 6つ目の観点は、素通りする入力と確かめる分岐を通らない ok の道の両方を名指しし、例の外の変種を反論役に作らせる
  view6=$(grep '^  6\. \*\*足した検査の素通り\*\*' <<<"$block")
  grep -qF '検査の見ていない書き方で書いた入力' <<<"$view6" || m="$m [観点 6 に素通りする入力]"
  grep -qF '確かめる分岐を通らずに ok になる道' <<<"$view6" || m="$m [観点 6 に分岐を通らない ok の道]"
  grep -qF '例の外も、検査の意味から変種を作って試す' <<<"$view6" || m="$m [観点 6 に例の外の変種を作らせること]"
  grep -q '^- \*\*確かめ方\*\*:.*落ちる検査を書けた疑いだけを直す.*落ちる検査を書けない疑い.*は捨て' <<<"$block" || m="$m [確かめ方: 落ちる検査を書けた疑いだけを直し、書けなければ捨てる]"
  # 検証の道の疑いは捨てずに地図で確かめ、足すか足さない理由をトレードオフに書く。扱いはこの項目に限る
  vpath=$(grep '^- \*\*当てたあとの検証の道の疑い\*\*:' <<<"$block")
  for n in '落ちる検査を書けなくても捨てない' '細かい機能の手順と段' '同じ PR で細かい機能か手順を足す' '理由を PR 本文の「トレードオフ」に書く' 'この扱いはこの項目の疑いだけ'; do
    grep -qF -- "$n" <<<"$vpath" || m="$m [検証の道の疑い: 「$n」]"
  done
  grep -q '^- \*\*サブエージェントを起動できないプロファイル\*\*.*自分で通す' <<<"$block" || m="$m [サブエージェントを起動できないときの通し方]"
  grep -q '^- \*\*残し方\*\*:.*`反論:` の行' <<<"$block" || m="$m [残し方: 報告の反論の行]"
  grep -q '^| 確認 |.*1回目を頼む前の反論の段（§4）' <<<"$s2" || m="$m [worker §2 の工程表の確認に反論の段]"
  grep -q '^3\. PR を出す（.*出す前に §4 の反論の段を通す' <<<"$s3" || m="$m [worker §3 の 3 に反論の段]"
  grep -q '^1\. PR を出したらすぐ頼む（反論の段〈上〉の行' <<<"$s4" || m="$m [worker §4 の 1 に反論の段の行]"
  grep -q '^反論: <.*疑い N 件.*直した M 件.*捨てた K 件.*1回目を頼むとき' <<<"$s7" || m="$m [worker §7 の書式に「反論:」の行]"
  # 自分で通した（Codex など）ときも REVIEW.md の項目を当てたかが、当てたあとの検証で報告から読めるよう、行に件数を書かせる
  grep -q '^反論: <.*疑い N 件（うち `REVIEW.md` の項目から L 件' <<<"$s7" || m="$m [worker §7 の「反論:」の行に REVIEW.md の項目の件数]"
  # 検証の道の疑いを地図に足したか・足さずにトレードオフに書いたかが、当てたあとの検証で報告から読めるよう、行に件数を書かせる
  grep -q '^反論: <.*検証の道の疑いは、地図に足した J 件と、足さずにトレードオフに書いた G 件' <<<"$s7" || m="$m [worker §7 の「反論:」の行に検証の道の疑いの件数]"
  echo "$m"
}
w=package/skills/worker/SKILL.md
miss=$(rebuttal_miss "$w")
[ -z "$miss" ] && pass "worker skill §4 に、1回目のレビューを頼む前の反論の段（渡すもの・6つの観点・REVIEW.md の項目・確かめ方・検証の道の疑い・サブエージェントが無いとき・残し方）があり、§2 の工程表・§3・§4 の 1・§7 の書式から指されている" || fail "反論の段:$miss"
# 検査が当たる場合があること: 段を消した・観点や確かめ方を抜いた・指す所を消した写しでは落ちる
miss=
sed '/^\*\*1回目を頼む前に、反論の段を通す\*\*/,/^1\. PR を出したらすぐ頼む/{/^1\. PR を出したらすぐ頼む/!d}' "$w" >"$tmp/worker.md"
[ -n "$(rebuttal_miss "$tmp/worker.md")" ] || miss="$miss [段を消した]"
for v in 包む呼び出し元 並行の実行 無い・空・読めない入力 片方だけ欠ける入力 たどる循環 足した検査の素通り; do
  grep -vF "**$v**" "$w" >"$tmp/worker.md"
  [ -n "$(rebuttal_miss "$tmp/worker.md")" ] || miss="$miss [観点「$v」を抜いた]"
done
# 直す前の skill の形: 観点が5つで、数の文も5つのまま
grep -vF '**足した検査の素通り**' "$w" | sed 's/6つの観点/5つの観点/g' >"$tmp/worker.md"
[ -n "$(rebuttal_miss "$tmp/worker.md")" ] || miss="$miss [観点を5つに戻した]"
sed 's/下の6つの観点の見落とし/下の5つの観点の見落とし/' "$w" >"$tmp/worker.md"
[ -n "$(rebuttal_miss "$tmp/worker.md")" ] || miss="$miss [段の頭の観点の数だけを古くした]"
sed 's/6つの観点ごとに疑いを/5つの観点ごとに疑いを/' "$w" >"$tmp/worker.md"
[ -n "$(rebuttal_miss "$tmp/worker.md")" ] || miss="$miss [自分で通すときの観点の数だけを古くした]"
sed '/^  6\. \*\*足した検査の素通り\*\*/s/確かめる分岐を通らずに ok になる道が無いか。//' "$w" >"$tmp/worker.md"
[ -n "$(rebuttal_miss "$tmp/worker.md")" ] || miss="$miss [観点 6 から分岐を通らない ok の道を消した]"
sed '/^  6\. \*\*足した検査の素通り\*\*/s/例の外も、検査の意味から変種を作って試す。//' "$w" >"$tmp/worker.md"
[ -n "$(rebuttal_miss "$tmp/worker.md")" ] || miss="$miss [観点 6 から例の外の変種を消した]"
sed 's/、repo に `REVIEW.md` があればそのパスだけ。/、repo に `REVIEW.md` があればそのパスと報告。/' "$w" >"$tmp/worker.md"
[ -n "$(rebuttal_miss "$tmp/worker.md")" ] || miss="$miss [渡すものに報告を足した]"
sed 's/落ちる検査を書けた疑いだけを直す/疑いを全部直す/' "$w" >"$tmp/worker.md"
[ -n "$(rebuttal_miss "$tmp/worker.md")" ] || miss="$miss [確かめ方を全部直すに変えた]"
# 直す前の skill の形: 渡すものに REVIEW.md が無い・項目の行が無い・自分で通すときに項目が無い
sed 's/と依頼書のパスと、repo に `REVIEW.md` があればそのパスだけ。/と依頼書のパスだけ。/' "$w" >"$tmp/worker.md"
[ -n "$(rebuttal_miss "$tmp/worker.md")" ] || miss="$miss [渡すものから REVIEW.md を消した]"
grep -v '^- \*\*`REVIEW.md` の項目\*\*' "$w" >"$tmp/worker.md"
[ -n "$(rebuttal_miss "$tmp/worker.md")" ] || miss="$miss [REVIEW.md の項目の行を消した]"
sed 's/、`REVIEW.md` があればその項目ごとにも書き出して/て/' "$w" >"$tmp/worker.md"
[ -n "$(rebuttal_miss "$tmp/worker.md")" ] || miss="$miss [自分で通すときの REVIEW.md の項目を消した]"
sed 's/疑い N 件（うち `REVIEW.md` の項目から L 件。`REVIEW.md` が無ければ書かない）のうち/疑い N 件のうち/' "$w" >"$tmp/worker.md"
[ -n "$(rebuttal_miss "$tmp/worker.md")" ] || miss="$miss [§7 の反論の行から REVIEW.md の件数を消した]"
# 直す前の skill の形: 検証の道の疑いの行が無く、落ちる検査を書けない疑いは全部捨てる
grep -v '^- \*\*当てたあとの検証の道の疑い\*\*' "$w" >"$tmp/worker.md"
[ -n "$(rebuttal_miss "$tmp/worker.md")" ] || miss="$miss [検証の道の疑いの行を消した]"
sed '/^- \*\*当てたあとの検証の道の疑い\*\*/s/落ちる検査を書けなくても捨てない/落ちる検査を書けなければ捨てる/' "$w" >"$tmp/worker.md"
[ -n "$(rebuttal_miss "$tmp/worker.md")" ] || miss="$miss [検証の道の疑いも捨てるに変えた]"
sed '/^- \*\*当てたあとの検証の道の疑い\*\*/s/足さないとき（作り直しでしか届かない変更など）は、理由を PR 本文の「トレードオフ」に書く。//' "$w" >"$tmp/worker.md"
[ -n "$(rebuttal_miss "$tmp/worker.md")" ] || miss="$miss [足さない理由をトレードオフに書くことを消した]"
sed '/^- \*\*当てたあとの検証の道の疑い\*\*/s/この扱いはこの項目の疑いだけで、ほかの疑いは上の確かめ方のとおり捨てる。//' "$w" >"$tmp/worker.md"
[ -n "$(rebuttal_miss "$tmp/worker.md")" ] || miss="$miss [扱いをこの項目に限ることを消した]"
sed 's/。検証の道の疑いは、地図に足した J 件と、足さずにトレードオフに書いた G 件（検証の道の疑いが無ければ書かない）//' "$w" >"$tmp/worker.md"
[ -n "$(rebuttal_miss "$tmp/worker.md")" ] || miss="$miss [§7 の反論の行から検証の道の件数を消した]"
grep -v '^- \*\*サブエージェントを起動できないプロファイル\*\*' "$w" >"$tmp/worker.md"
[ -n "$(rebuttal_miss "$tmp/worker.md")" ] || miss="$miss [サブエージェントが無いときを消した]"
sed 's/・`Review: on` は1回目を頼む前の反論の段（§4）//' "$w" >"$tmp/worker.md"
[ -n "$(rebuttal_miss "$tmp/worker.md")" ] || miss="$miss [工程表の確認から消した]"
sed 's/。`Review: on` なら、出す前に §4 の反論の段を通す）/）/' "$w" >"$tmp/worker.md"
[ -n "$(rebuttal_miss "$tmp/worker.md")" ] || miss="$miss [§3 の 3 から消した]"
sed 's/（反論の段〈上〉の行と、/（/' "$w" >"$tmp/worker.md"
[ -n "$(rebuttal_miss "$tmp/worker.md")" ] || miss="$miss [§4 の 1 から消した]"
grep -v '^反論: <' "$w" >"$tmp/worker.md"
[ -n "$(rebuttal_miss "$tmp/worker.md")" ] || miss="$miss [§7 の行を消した]"
[ -z "$miss" ] && pass "反論の段: 段・観点・渡すもの・REVIEW.md の項目・確かめ方・検証の道の疑い・サブエージェントが無いとき・工程表と §3 と §4 の 1 と §7 の行を崩した写しでは落ちる（検査が見ている）" || fail "反論の段: 写しで落ちない:$miss"
